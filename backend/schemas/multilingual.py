from typing import Optional, List, Dict, Any, Literal
from pydantic import BaseModel, Field


class TranscriptionResult(BaseModel):
    """Result of audio speech-to-text transcription."""
    transcript: str = Field(..., description="Recognized speech text in original language")
    detected_language: str = Field("en", description="Detected language code (e.g. 'en', 'hi', 'ur')")
    language_probability: Optional[float] = Field(None, description="Confidence of detected language")
    confidence: Optional[float] = Field(None, description="Average token confidence score (0.0 to 1.0) or None if unavailable")
    duration_seconds: float = Field(0.0, description="Audio duration in seconds")
    model_size: str = Field("base", description="Whisper model size used: 'base' or 'tiny'")
    source_type: Literal["voice_transcript"] = "voice_transcript"
    is_mock: bool = Field(False, description="True if generated by mock transcription engine")
    segments: List[Dict[str, Any]] = Field(default_factory=list, description="Word/phrase segments with timestamps")


class DocumentExtractionResult(BaseModel):
    """Result of document OCR or text extraction before confirmation."""
    filename: str = Field(..., description="Original filename of the uploaded report")
    extracted_text: str = Field(..., description="Extracted clinical document text")
    char_count: int = Field(..., description="Number of characters extracted")
    engine_used: str = Field(..., description="OCR engine utilized: 'winocr', 'paddleocr', 'pypdf', or 'mock'")
    confidence: float = Field(1.0, description="Estimated extraction confidence (0.0 to 1.0)")
    source_type: Literal["ocr_extraction"] = "ocr_extraction"
    is_mock: bool = Field(False, description="True if generated in mock environment")


class ConfirmedMessageRequest(BaseModel):
    """Request payload when submitting patient input after review/confirmation."""
    content: str = Field(..., min_length=1, description="Patient message text (typed, voice confirmed, or OCR confirmed)")
    source_type: Literal["patient_typed", "voice_transcript", "ocr_extraction"] = Field(
        "patient_typed",
        description="Provenance of the message content"
    )
    source_language: Optional[str] = Field(None, description="Reported or detected language code")
    confidence: Optional[float] = Field(None, description="Confidence score if originated from ASR or OCR")
    is_confirmed: bool = Field(True, description="Indicates whether the patient reviewed and confirmed the text")
